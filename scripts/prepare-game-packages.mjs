import { cpSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repository = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Stage canonical workspace sources into the existing Hosting and npm deployment roots. */
export function prepareGamePackages(root = repository) {
  const rules = [
    ["game-common/src/hexGrid.ts", "hexGrid.ts"],
    ["buzzello/src/rules.ts", "buzzello.ts"],
    ["buzzle/src/rules.ts", "buzzle.ts"],
  ];
  for (const [source, name] of rules) {
    const target = resolve(root, "functions/src/generated/games", name);
    const content = readFileSync(resolve(root, "packages", source), "utf8")
      .replaceAll('"@ares/game-common/hex-grid"', '"./hexGrid"');
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, "// Generated by games:prepare; edit the canonical package source.\n" + content);
  }
  cpSync(resolve(root, "packages/pollenator/public"), resolve(root, "public/games/pollen"), { recursive: true });
  for (const destination of ["public/data", "functions/data"]) {
    mkdirSync(resolve(root, destination), { recursive: true });
    cpSync(resolve(root, "packages/buzzle/data/buzzle-words.txt"), resolve(root, destination, "buzzle-words.txt"));
  }
  cpSync(resolve(root, "packages/buzzle/data/buzzle-words.meta.json"), resolve(root, "public/data/buzzle-words.meta.json"));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) prepareGamePackages();
